"""Capture README screenshots from the running app.

Screenshots are generated by a script rather than taken by hand so they stay
current: when the UI changes, re-run this instead of remembering which four
pictures need retaking.

Requires the app to be running and Playwright's Chromium to be installed:

    .venv/Scripts/python -m pip install playwright
    .venv/Scripts/python -m playwright install chromium
    .venv/Scripts/streamlit run app.py        # in another terminal

Then, from the repo root:

    .venv/Scripts/python scripts/capture_screenshots.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from playwright.sync_api import Page, sync_playwright

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "docs" / "screenshots"

VIEWPORT = {"width": 1440, "height": 900}
SETTLE_MS = 2500          # Streamlit re-runs and Plotly animates after load


def _wait(page: Page, ms: int = SETTLE_MS) -> None:
    page.wait_for_load_state("networkidle")
    page.wait_for_timeout(ms)


def _pick(page: Page, label: str, contains: str) -> None:
    """Choose an option in a Streamlit selectbox by its visible label."""
    box = page.get_by_label(label, exact=True).first
    box.click()
    page.wait_for_timeout(400)
    box.type(contains, delay=25)
    page.wait_for_timeout(700)
    page.get_by_role("option").first.click()
    _wait(page)


def capture(base_url: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport=VIEWPORT, device_scale_factor=2)

        # 1. Home
        page.goto(base_url, wait_until="networkidle")
        _wait(page)
        page.screenshot(path=OUT_DIR / "01-home.png")
        print("  01-home.png")

        # 2. Player search, with a reference player chosen
        page.goto(f"{base_url}/player_search", wait_until="networkidle")
        _wait(page)
        _pick(page, "Player", "Vardy")
        page.screenshot(path=OUT_DIR / "02-player-search.png")
        print("  02-player-search.png")

        # 3. Player comparison, two strikers side by side
        page.goto(f"{base_url}/player_comparison", wait_until="networkidle")
        _wait(page)
        _pick(page, "Role group", "ST")
        _pick(page, "Player A", "Vardy")
        _pick(page, "Player B", "Kane")
        page.screenshot(path=OUT_DIR / "03-player-comparison.png")
        print("  03-player-comparison.png")

        # 4. Team style map
        page.goto(f"{base_url}/team_style_map", wait_until="networkidle")
        _wait(page)
        page.screenshot(path=OUT_DIR / "04-team-style-map.png")
        print("  04-team-style-map.png")

        # 5. Team profile for the champions
        page.goto(f"{base_url}/team_profile", wait_until="networkidle")
        _wait(page)
        _pick(page, "Team", "Leicester")
        page.screenshot(path=OUT_DIR / "05-team-profile.png")
        print("  05-team-profile.png")

        browser.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default="http://localhost:8501",
                        help="base URL of the running app")
    args = parser.parse_args()

    print(f"Capturing screenshots from {args.url} into {OUT_DIR}")
    try:
        capture(args.url.rstrip("/"))
    except Exception as exc:
        print(f"\nCapture failed: {exc}")
        print("Is the app running?  .venv/Scripts/streamlit run app.py")
        sys.exit(1)
    print("Done.")


if __name__ == "__main__":
    main()
