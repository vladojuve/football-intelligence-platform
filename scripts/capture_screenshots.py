"""Capture README screenshots from the running app.

Screenshots are generated by a script rather than taken by hand so they stay
current: when the UI changes, re-run this instead of remembering which pictures
need retaking.

Requires the app to be running and Playwright's Chromium to be installed:

    .venv/Scripts/python -m pip install playwright
    .venv/Scripts/python -m playwright install chromium
    .venv/Scripts/streamlit run app.py        # in another terminal

Then, from the repo root:

    .venv/Scripts/python scripts/capture_screenshots.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from urllib.parse import quote_plus

from playwright.sync_api import Page, sync_playwright

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "docs" / "screenshots"

VIEWPORT = {"width": 1440, "height": 950}
SETTLE_MS = 2500          # Streamlit re-runs and Plotly animates after load

# Pages that link to each other by id rather than by name, so the script can
# open them directly instead of clicking its way there.
KANTE_ID = 3961
LEICESTER = "Leicester City"
# Manchester City 1-3 Leicester City, matchweek 25: a lopsided-possession match,
# so the mirrored style chart in the report has something to show.
MATCH_ID = 3754290


def _wait(page: Page, ms: int = SETTLE_MS, charts: int = 0) -> None:
    """Settle the page, and wait for Plotly to actually draw if asked.

    `networkidle` fires while Streamlit is still showing its grey skeleton
    boxes, so a screenshot taken then catches the placeholders rather than the
    charts. Waiting for the expected number of rendered plots is the only
    reliable signal, since Streamlit streams elements in as they are produced.
    """
    page.wait_for_load_state("networkidle")
    if charts:
        page.wait_for_function(
            "count => document.querySelectorAll('.js-plotly-plot').length >= count",
            arg=charts, timeout=60_000,
        )
    page.wait_for_timeout(ms)


def _scroll_to(page: Page, heading: str, extra: int = 0) -> None:
    """Bring a section into view, for the pages whose point is below the fold.

    `extra` scrolls further after the heading is at the top, for sections whose
    heading and caption alone fill most of the viewport.
    """
    page.get_by_text(heading, exact=True).first.scroll_into_view_if_needed()
    if extra:
        # Streamlit scrolls its own main container, not the window, so a mouse
        # wheel event on the page body moves nothing.
        page.evaluate(
            """(amount) => {
                const main = document.querySelector('[data-testid="stMain"]')
                    || document.scrollingElement;
                main.scrollTop += amount;
            }""",
            extra,
        )
    page.wait_for_timeout(1200)


def _pick(page: Page, label: str, contains: str) -> None:
    """Choose an option in a Streamlit selectbox by its visible label."""
    box = page.get_by_label(label, exact=True).first
    box.click()
    page.wait_for_timeout(400)
    box.type(contains, delay=25)
    page.wait_for_timeout(700)
    page.get_by_role("option").first.click()
    _wait(page)


def _shot(page: Page, name: str) -> None:
    page.screenshot(path=OUT_DIR / name)
    print(f"  {name}")


def capture(base_url: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport=VIEWPORT, device_scale_factor=2)

        # 1. Home, with a search that shows the accent-tolerant matching working
        page.goto(base_url, wait_until="networkidle")
        _wait(page)
        page.get_by_placeholder("Try", exact=False).fill("Ngolo Kante")
        page.keyboard.press("Enter")
        _wait(page)
        _shot(page, "01-home.png")

        # 2. Player profile: the twelve percentile rings
        page.goto(f"{base_url}/player_profile?player={KANTE_ID}",
                  wait_until="networkidle")
        _wait(page, charts=12)
        _scroll_to(page, "Percentile profile", extra=320)
        _shot(page, "02-player-profile.png")

        # 3. Similarity search
        page.goto(f"{base_url}/player_search?player={KANTE_ID}",
                  wait_until="networkidle")
        _wait(page)
        _shot(page, "03-player-search.png")

        # 4. Player comparison, two strikers side by side
        page.goto(f"{base_url}/player_comparison", wait_until="networkidle")
        _wait(page)
        _pick(page, "Role group", "ST")
        _pick(page, "Player A", "Vardy")
        _pick(page, "Player B", "Kane")
        _wait(page, charts=2)
        _scroll_to(page, "Profile")
        _shot(page, "04-player-comparison.png")

        # 5. Club profile for the champions
        page.goto(f"{base_url}/team_profile?team={quote_plus(LEICESTER)}",
                  wait_until="networkidle")
        _wait(page, charts=10)
        _scroll_to(page, "Special players", extra=60)
        _shot(page, "05-club-profile.png")

        # 6. Team style map
        page.goto(f"{base_url}/team_style_map", wait_until="networkidle")
        _wait(page, charts=1)
        _shot(page, "06-team-style-map.png")

        # 7. A match report, not the fixture list — the list is the way in, the
        # report is the thing worth showing.
        page.goto(f"{base_url}/matches?match={MATCH_ID}", wait_until="networkidle")
        _wait(page, charts=1)
        _shot(page, "07-match-report.png")

        browser.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default="http://localhost:8501",
                        help="base URL of the running app")
    args = parser.parse_args()

    print(f"Capturing screenshots from {args.url} into {OUT_DIR}")
    try:
        capture(args.url.rstrip("/"))
    except Exception as exc:
        print(f"\nCapture failed: {exc}")
        print("Is the app running?  .venv/Scripts/streamlit run app.py")
        sys.exit(1)
    print("Done.")


if __name__ == "__main__":
    main()
